package com.atguigu.java.day2.base_grammar;


public class Demo07_OperatorAdd {

    public static void main(String[] args) {
        // 1、+号做数学运算
        int a = 10;
        int b = 5;
        System.out.println(a + b);

        // 2、+号做字符串连接
        String info = "Tom's age is:";
        int age = 18;
        System.out.println(info + age);
    }

}
