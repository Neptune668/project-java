package com.atguigu.java.day2.base_grammar;

/*
 * Java 中的多行注释
 * Java 中写代码的铁律
 * 1、任何代码都必须写在类中
 * 2、任何需要执行的代码都必须写在方法（函数）中
 * 需要执行的代码：数学运算、打印、调用方法、执行 SQL 语句……
 * 3、Java 程序的入口是 main 函数
 */
public class Demo01_HelloWorld {

    // Java 中的单行注释
    // main 方法的声明必须严格和下面代码一致！
    public static void main(String[] args) {
        // 在控制台打印 HelloWorld…… 字符串
        System.out.println("HelloWorld……");
    }

}
