package com.atguigu.java.test;

public class Demo02_DataType {

    public static void main(String[] args) {
        // 1、打印 byte 类型的数据
        byte dataByte = 50;
        System.out.println("byte 类型的数据 = " + dataByte);

        // 2、打印 short 类型的数据
        short dataShort = 200;
        System.out.println("short 类型的数据 = " + dataShort);

        // 3、打印 int 类型的数据
        System.out.println("int 类型的数据：" + 50000);

        // 4、打印 long 类型的数据
        System.out.println("long 类型的数据：" + 99998888L);

        // 5、打印 float 类型的数据
        System.out.println("float 类型的数据：" + 8888.88f);

        // 6、打印 double 类型的数据
        System.out.println("double 类型的数据：" + 5555.55);

        // 7、打印 char 类型的数据
        System.out.println("char 类型的数据：" + '牛');

        // 8、打印 boolean 类型的数据
        System.out.println("boolean 类型的数据：" + true);
        System.out.println("boolean 类型的数据：" + false);
    }

}
